//! Exports SVG snapshots for the controls **this crate** registers.
//!
//! # Why this is a second exporter
//!
//! `examples/export_control_svgs.rs` in the parent crate walks the parent's registry. The
//! suites live in this package (the dependency runs one way), so a control the suite registers
//! cannot appear in that set at all — `map_view`, `kanban_board`, `video_player` and the rest had
//! no committed picture, which left the cookbook's entries for them without an image.
//!
//! This exporter asks a factory that has [`install`](rust_widgets_suites::install) applied, keeps
//! only the names the **parent** does not already own, and writes the same artifact shape the
//! parent's exporter writes: `<name>.svg` is the dark appearance, `<name>.light.svg` the light
//! one, each with a provenance comment naming this producer.
//!
//! # Regenerating
//!
//! ```text
//! cargo run --manifest-path crates/rust-widgets-suites/Cargo.toml --no-default-features \
//!     --features "finance,maps,project,devtools,media-playback,webview" \
//!     --example export_suite_svgs
//! ```
//!
//! `tools/check_suite_snapshots.sh` runs exactly that and requires the committed files to match
//! byte for byte, so a changed control shows up as a diff instead of a stale picture.
//!
//! # Where the files go
//!
//! `snapshots/suite-svg/`, next to — not inside — the parent's `snapshots/svg/`. The parent's set
//! is "the pictures of what a plain `cargo build` produces"; these controls need six optional
//! suite features, so folding them into that set would make its central claim false. The cookbook
//! copies the dark file of each control from whichever directory owns it.

use std::fs;
use std::path::Path;

use rust_widgets::core::Color;
use rust_widgets::theme::{
    apply_theme_to_widget, global_theme_manager, theme_test_guard, AppearanceMode,
};
use rust_widgets::widget::census::{install_preset_appearances, CENSUS_RECT, CENSUS_TEXT};
use rust_widgets::widget::draw_bridge::draw_of;
use rust_widgets::widget::svg::render_widget_to_svg_on;
use rust_widgets::widget::WidgetFactory;

/// Where the suite snapshots live, relative to **this package's manifest**.
///
/// Anchored to `CARGO_MANIFEST_DIR` rather than the process working directory: `cargo run
/// --manifest-path …` keeps the caller's cwd, so a relative path would write outside the
/// repository depending on where the gate was started.
const OUTPUT_DIR_RELATIVE: &str = "../../snapshots/suite-svg";

/// The marker every generated file carries, so it is recognisable as an artifact.
const GENERATED_MARKER: &str =
    "<!-- GENERATED by crates/rust-widgets-suites/examples/export_suite_svgs.rs -->";

/// How long one settle tick advances a control's transition, in milliseconds.
const SETTLE_TICK_MS: u32 = 16;

/// The most settle ticks spent on one control (the same bound the parent exporter uses).
const MAX_SETTLE_TICKS: usize = 64;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Serialises against any other test or probe that switches the process-wide theme.
    let _guard = theme_test_guard();
    install_preset_appearances();

    // The parent's registry, so the suite-only names are the difference rather than a second
    // hand-typed list that would drift the day a group adds a control.
    let parent = WidgetFactory::new_with_defaults();
    let parent_names: std::collections::HashSet<&str> = parent.widget_names().into_iter().collect();
    let factory = WidgetFactory::new_with_extensions(&[rust_widgets_suites::install])?;
    let mut names: Vec<&'static str> =
        factory.widget_names().into_iter().filter(|name| !parent_names.contains(name)).collect();
    names.sort_unstable();

    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join(OUTPUT_DIR_RELATIVE);
    fs::create_dir_all(&dir)?;
    // A canonical path reads cleanly in the log line (`crates/…/../../snapshots` does not).
    let dir = fs::canonicalize(&dir).unwrap_or(dir);

    let mut written = 0usize;
    let mut failed: Vec<String> = Vec::new();

    for name in &names {
        for (appearance, suffix) in [(AppearanceMode::Dark, ""), (AppearanceMode::Light, ".light")]
        {
            global_theme_manager().set_appearance(appearance);
            let Some(mut widget) = factory.create(name, CENSUS_RECT, CENSUS_TEXT) else {
                failed
                    .push(format!("{name}: the registry publishes it but `create` returned None"));
                continue;
            };
            // The theme is applied the way the runtime applies it (after construction), so the
            // two appearances describe what a user gets.
            apply_theme_to_widget(widget.as_mut());

            // A control that started an animation in its constructor is settled before drawing,
            // so the committed picture is reproducible rather than a frame of the run.
            for _ in 0..MAX_SETTLE_TICKS {
                if !widget.is_animating() {
                    break;
                }
                let _ = widget.tick(SETTLE_TICK_MS);
            }

            let Some(drawable) = draw_of(widget.as_mut()) else {
                failed.push(format!("{name}: the widget has no `Draw` implementation"));
                continue;
            };
            let backdrop = global_theme_manager()
                .current_theme()
                .map(|active| active.colors.background)
                .unwrap_or(Color::WHITE);
            let body = render_widget_to_svg_on(drawable, CENSUS_RECT, backdrop);
            let label = match appearance {
                AppearanceMode::Dark => "dark",
                AppearanceMode::Light => "light",
            };
            let document = format!(
                "{GENERATED_MARKER}\n<!-- control: {name} | appearance: {label} -->\n{body}\n"
            );
            fs::write(dir.join(format!("{name}{suffix}.svg")), document)?;
            written += 1;
        }
    }

    println!(
        "wrote {written} suite SVG snapshots for {} control(s) into {}/",
        names.len(),
        dir.display()
    );
    if !failed.is_empty() {
        for failure in &failed {
            eprintln!("error: {failure}");
        }
        return Err(format!(
            "{} suite control(s) could not be exported; refusing to leave a partial set",
            failed.len()
        )
        .into());
    }
    Ok(())
}
