//!
//! Shared paint-role resolution for the Gantt companion controls.

use rust_widgets::core::Color;

/// Resolves the surface, border and ink a gantt companion paints with.
pub(super) fn chart_chrome_palette(
    style: &rust_widgets::style::WidgetStyle,
    role: &str,
) -> (Color, Color, Color) {
    let theme = rust_widgets::style::resolved_theme_style_shared(role);
    let ink = style
        .text_color
        .or_else(|| theme.as_ref().and_then(|t| t.text_color))
        .unwrap_or(Color::rgb(45, 58, 74));
    let border = style
        .border_color
        .or_else(|| theme.as_ref().and_then(|t| t.border_color))
        .unwrap_or(Color::rgb(168, 184, 201));
    let surface = style
        .background_color
        .or_else(|| theme.as_ref().and_then(|t| t.background_color))
        .unwrap_or(Color::rgb(235, 243, 250));
    (surface, border, ink)
}
