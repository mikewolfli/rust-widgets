/// Applies the state an extra appearance depicts. Returns `false` when the control does not have
/// the state, which is reported rather than silently skipped.
fn apply_extra_state(
    control: &str,
    suffix: &str,
    widget: &mut dyn rust_widgets::widget::Widget,
) -> bool {
    match (control, suffix) {
        ("icon", "_info") => {
            use rust_widgets::widget::{Icon, IconName};
            match rust_widgets::widget::capability::coercion::widget_as_mut::<Icon>(widget) {
                Some(icon) => {
                    icon.set_icon_enum(IconName::Info);
                    true
                }
                None => false,
            }
        }
        ("group_box", "_checked") => {
            use rust_widgets::widget::container_widgets::groupbox::GroupBox;
            match rust_widgets::widget::capability::coercion::widget_as_mut::<GroupBox>(widget) {
                Some(group_box) => {
                    group_box.set_checkable(true);
                    group_box.set_checked(true);
                    true
                }
                None => false,
            }
        }
        // The toggles, each through its own `set_checked`. The string in `EXTRA_APPEARANCES` and the
        // state that is drawn cannot disagree, because the arm names the state and the control is
        // asked for it by its published name — a mismatch would produce a snapshot of the *off* state
        // under a name that says `on`, which is the one failure this has to rule out.
        ("radio_button", "_checked") => {
            use rust_widgets::widget::base_widgets::radiobutton::RadioButton;
            match rust_widgets::widget::capability::coercion::widget_as_mut::<RadioButton>(widget) {
                Some(radio) => {
                    radio.set_checked(true);
                    true
                }
                None => false,
            }
        }
        ("toggle_button", "_checked") => {
            use rust_widgets::widget::base_widgets::toggle_button::ToggleButton;
            match rust_widgets::widget::capability::coercion::widget_as_mut::<ToggleButton>(widget)
            {
                Some(button) => {
                    button.set_checked(true);
                    true
                }
                None => false,
            }
        }
        // The three frame shapes that paint a fill, each reached through the control's own
        // `from_name`, so the string in `EXTRA_APPEARANCES` and the shape that is drawn cannot
        // disagree — a mismatch would produce a snapshot of the *default* shape under a name that
        // claims otherwise, which is the one failure mode this arm has to rule out.
        ("frame", "_styled_panel" | "_win_panel" | "_panel") => {
            use rust_widgets::widget::base_widgets::frame::{Frame, FrameShape};
            let shape = FrameShape::from_name(&suffix[1..]).expect("a name from EXTRA_APPEARANCES");
            match rust_widgets::widget::capability::coercion::widget_as_mut::<Frame>(widget) {
                Some(frame) => {
                    frame.set_frame_shape(shape);
                    true
                }
                None => false,
            }
        }
        // A shown tooltip is the state a user sees, and it is reached through the control's own
        // `show`, so the string in `EXTRA_APPEARANCES` and the state drawn cannot disagree.
        ("tooltip", "_shown") => {
            use rust_widgets::widget::dialog::tooltip::Tooltip;
            match rust_widgets::widget::capability::coercion::widget_as_mut::<Tooltip>(widget) {
                Some(tooltip) => {
                    tooltip.show();
                    true
                }
                None => false,
            }
        }
        ("skeleton_loader", "_circle") => {
            use rust_widgets::widget::display_widgets::skeleton_loader::{
                SkeletonLoader, SkeletonShape,
            };
            match rust_widgets::widget::capability::coercion::widget_as_mut::<SkeletonLoader>(
                widget,
            ) {
                Some(skeleton) => {
                    skeleton.set_shape(SkeletonShape::Circle(18));
                    true
                }
                None => false,
            }
        }
        ("skeleton_loader", "_textline") => {
            use rust_widgets::widget::display_widgets::skeleton_loader::{
                SkeletonLoader, SkeletonShape,
            };
            match rust_widgets::widget::capability::coercion::widget_as_mut::<SkeletonLoader>(
                widget,
            ) {
                Some(skeleton) => {
                    skeleton.set_shape(SkeletonShape::TextLine(160));
                    true
                }
                None => false,
            }
        }
        _ => false,
    }
}

/// One companion in a pair scene.
///
/// Most companions are full `Widget`s, so the scene advances and themes them the way the
/// runtime does. The four model-only input companions (`Chip`, `StepButtons`, `Scrollbar`,
/// `FormatToolbar`) paint through their own `Draw` impl and own no `BaseWidget`, so they carry
/// only that paint entry.
enum Companion {
    Widget(Box<dyn Widget>),
    Painted(Box<dyn Draw>),
}

impl Companion {
    /// Applies the active theme and settles a companion that owns animation state.
    fn prepare(&mut self) {
        if let Companion::Widget(widget) = self {
            rust_widgets::theme::apply_theme_to_widget(widget.as_mut());
            for _ in 0..MAX_SETTLE_TICKS {
                if !widget.is_animating() {
                    break;
                }
                let _ = widget.tick(SETTLE_TICK_MS);
            }
        }
    }

    /// Paints the companion into the scene's shared context.
    fn draw(&mut self, context: &mut RenderContext) {
        match self {
            Companion::Widget(widget) => {
                if let Some(drawable) = draw_of(widget.as_mut()) {
                    drawable.draw(context);
                }
            }
            Companion::Painted(drawable) => drawable.draw(context),
        }
    }
}

/// A primary control and the companion that belongs beside it, plus the paint order.
struct PairScene {
    primary: Box<dyn Widget>,
    companion: Companion,
    /// Whether the companion paints *behind* the primary. A modal scrim and a swipe-action
    /// background are the two cases: both are chrome the primary sits on top of.
    companion_behind: bool,
}

impl PairScene {
    fn new(primary: Box<dyn Widget>, companion: Companion, companion_behind: bool) -> Self {
        Self { primary, companion, companion_behind }
    }
}

/// Builds the scene one pair entry describes.
///
/// Every arm uses the companion's own public constructor and the geometry it documents (an
