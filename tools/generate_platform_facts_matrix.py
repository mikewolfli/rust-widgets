"""Generate the platform-facts matrix (BLUE28 B28.30).

The matrix answers one question per `Platform` method and backend: is this fact answered here by a
real override, by the shared `impl_platform_state_properties!` expansion, or by the trait default?
It is generated from the source so a new method or a deleted override cannot leave the document
behind.
"""

from __future__ import annotations

import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TYPES = ROOT / "src/platform/types.rs"
STATE_IMPL = ROOT / "src/platform/state_impl.rs"

BACKENDS = [
    ("Windows", "src/platform/windows/platform_impl.rs"),
    ("macOS cocoa", "src/platform/macos/platform_impl.rs"),
    ("macOS objc2", "src/platform/macos_objc2/platform_impl.rs"),
    ("GTK/X11", "src/platform/linux/platform_impl.rs"),
    ("Wayland", "src/platform/wayland/platform_impl.rs"),
    ("Android", "src/platform/android/platform_impl.rs"),
    ("Harmony", "src/platform/harmony/platform_impl.rs"),
    ("iOS", "src/platform/ios/platform_impl.rs"),
    ("Redox", "src/platform/redox/platform_impl.rs"),
    ("WASM", "src/platform/wasm/platform_impl.rs"),
    ("mobile", "src/platform/mobile.rs"),
    ("stub", "src/platform/stub.rs"),
]


def trait_methods() -> list[str]:
    text = TYPES.read_text(encoding="utf-8")
    start = text.index("pub trait Platform")
    # The trait ends at the top-level closing brace; the file has no nested `pub trait` after it.
    body = text[start:]
    # Stop at the first line that starts with `}` at column 0.
    end = re.search(r"^}\s*$", body, re.MULTILINE)
    body = body[: end.start()] if end else body
    return re.findall(r"^\s{4}fn ([a-z_0-9]+)\s*\(", body, re.MULTILINE)


def macro_methods() -> set[str]:
    text = STATE_IMPL.read_text(encoding="utf-8")
    return set(re.findall(r"fn ([a-z_0-9]+)\s*\(", text))


def overridden(path: str) -> set[str]:
    file = ROOT / path
    if not file.exists():
        return set()
    text = file.read_text(encoding="utf-8")
    return set(re.findall(r"fn ([a-z_0-9]+)\s*\(", text))


def uses_state_macro(path: str) -> bool:
    file = ROOT / path
    if not file.exists():
        return False
    return "impl_platform_state_properties!" in file.read_text(encoding="utf-8")


def render() -> str:
    methods = trait_methods()
    macro = macro_methods()
    data: dict[str, tuple[set[str], bool]] = {}
    for name, path in BACKENDS:
        data[name] = (overridden(path), uses_state_macro(path))

    lines = [
        "# Platform facts matrix (generated)",
        "",
        "Generated by `tools/generate_platform_facts_matrix.py`. **Do not edit by hand.**",
        "",
        "Legend: `✅` real override · `M` shared `impl_platform_state_properties!` expansion · "
        "`·` trait default (honest absence) · `-` backend file is absent.",
        "",
        f"`Platform` methods: **{len(methods)}**.",
        "",
        "| method | " + " | ".join(name for name, _ in BACKENDS) + " |",
        "|---|" + "|".join(":--:" for _ in BACKENDS) + "|",
    ]
    for method in methods:
        cells = []
        for name, path in BACKENDS:
            if not (ROOT / path).exists():
                cells.append("-")
                continue
            overrides, state_macro = data[name]
            if method in overrides:
                cells.append("✅")
            elif state_macro and method in macro:
                cells.append("M")
            else:
                cells.append("·")
        lines.append(f"| `{method}` | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Counts",
        "",
        "| backend | real overrides | macro-covered | default |",
        "|---|---:|---:|---:|",
    ]
    for name, path in BACKENDS:
        if not (ROOT / path).exists():
            lines.append(f"| {name} | - | - | - |")
            continue
        overrides, state_macro = data[name]
        real = sum(1 for method in methods if method in overrides)
        macro_count = sum(
            1 for method in methods if method not in overrides and state_macro and method in macro
        )
        default = len(methods) - real - macro_count
        lines.append(f"| {name} | {real} | {macro_count} | {default} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default=str(ROOT / "docs/plans/platform_facts_matrix.md"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    output = pathlib.Path(args.output)
    if args.check:
        if not output.exists():
            print(f"FAIL: {output} is missing; run the generator")
            return 1
        if output.read_text(encoding="utf-8") != rendered:
            print(f"FAIL: {output} is stale; run tools/generate_platform_facts_matrix.py")
            return 1
        print(f"PASS: {output} matches the source")
        return 0
    output.write_text(rendered, encoding="utf-8")
    print(f"wrote {output} ({len(trait_methods())} Platform methods)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
