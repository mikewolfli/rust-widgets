#!/usr/bin/env python3
"""Every control that holds a scroll position must declare its **unit** (RW-58).

# The gap this closes

`ScrollableSurface` (pixels) and `ScrollableRows` (rows) are the two units a container can
genuinely scroll in. A container that stores a `scroll_offset`/`scroll_row`/`scroll_position` field
but implements neither has no shared contract: restoring its position requires knowing the concrete
type, which is the per-control branching RW-58 exists to remove.

# How the census is built

1. Every `pub struct` with a field named for a scroll position is a **candidate**.
2. A candidate passes when it implements `ScrollableSurface` or `ScrollableRows`.
3. A candidate that cannot implement either — because its unit is not pixels or rows — must be
   named in `SCROLL_EXCLUDED` with the reason the unit does not fit.

`ROW-UNIT GAP` marks a candidate whose unit *is* rows but whose row API is still private; it is
excluded so the ledger is complete, and the gate prints the count so the gap is never read as
coverage.

# Reverse injection

`--inject=<canonical>` removes one exclusion on paper and requires a failure.

Run from the repository root.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import setter_census  # noqa: E402

SRC = pathlib.Path(__file__).resolve().parent.parent / "src"

SCROLL_FIELD = re.compile(
    r"\b(scroll_offset|scroll_row|scroll_column|scroll_position|scroll_pos|scroll_x|scroll_y"
    r"|first_visible_row|first_visible_line|scroll_top)\b\s*:"
)
PUB_STRUCT = re.compile(r"\bpub struct\s+([A-Z][A-Za-z0-9_]*)[^{;]*\{")

# Candidates whose unit is not a row index. The reason states the unit, so a later reader can tell
# "cannot" from "not yet".
SCROLL_EXCLUDED: dict[str, str] = {
    "code_editor": "text editor: the unit is a visual line, exposed by `first_visible_line`",
    "line_edit": "single-line field: `scroll_x` is a horizontal pixel offset",
    "markdown_editor": "text editor: the unit is a visual line, not a row index",
    "rich_edit": "text editor: the unit is a visual line, not a row index",
    "text_area": "text editor: the unit is a visual line, exposed by `first_visible_line`",
    "text_edit": "text editor: the unit is a visual line, exposed by `first_visible_row`",
    "tab_bar": "horizontal tab strip: the offset is a pixel position along the strip",
    "segmented_control": "horizontal overflow: the offset moves segments along a strip",
    "drop_down_popup_host": "fractional popup scroll (`f32`, 0..1), not a row index",
    "font_preview": "pixel scroll over variable-height font samples; no uniform row",
    "grid": "internal layout helper: its offset is a layout phase, not a scroll position",
    "command_palette_host": "host wrapper: the wrapped `command_palette` owns the row state",
    "cascader": "one offset per column level (`Vec`), so there is no single row index",
}



def source_texts() -> dict[pathlib.Path, str]:
    return {path: setter_census.strip_comments(path.read_text()) for path in SRC.rglob("*.rs")}


def candidate_structs(texts: dict[pathlib.Path, str]) -> dict[str, pathlib.Path]:
    found: dict[str, pathlib.Path] = {}
    for path, text in texts.items():
        for match in PUB_STRUCT.finditer(text):
            body = setter_census.brace_block(text, text.index("{", match.end() - 1))
            if SCROLL_FIELD.search(body):
                found.setdefault(match.group(1), path)
    return found


def trait_impls(texts: dict[pathlib.Path, str]) -> tuple[set[str], set[str]]:
    rows: set[str] = set()
    surface: set[str] = set()
    for text in texts.values():
        rows.update(re.findall(r"\bimpl\s+ScrollableRows\s+for\s+([A-Z][A-Za-z0-9_]*)", text))
        # The row containers reused by many suites are generated by the shared macro; its first
        # argument is the implementing type.
        rows.update(
            re.findall(r"crate::impl_scrollable_rows!\(\s*([A-Z][A-Za-z0-9_]*)", text)
        )
        surface.update(re.findall(r"\bimpl\s+ScrollableSurface\s+for\s+([A-Z][A-Za-z0-9_]*)", text))
    return rows, surface


def build(ignore_exclusion: str | None = None):
    texts = source_texts()
    candidates = candidate_structs(texts)
    rows, surface = trait_impls(texts)
    caps = setter_census.parse_capabilities()
    ctors = setter_census.parse_constructor_structs()
    registered = {}
    for cap_name, ctor in setter_census.parse_registrations():
        cap = caps.get(cap_name)
        struct = ctors.get(ctor)
        if cap and struct:
            registered[cap["canonical"]] = struct

    entries = []
    # Aliases (`context_menu` -> `Menu`, `password_edit` -> `LineEdit`) share the struct, so an
    # exclusion stated once covers every row that addresses the same implementation.
    excluded_structs: dict[str, str] = {}
    for canonical, reason in SCROLL_EXCLUDED.items():
        struct = registered.get(canonical)
        if struct:
            excluded_structs.setdefault(struct, reason)
    for canonical, struct in sorted(registered.items()):
        if struct not in candidates:
            continue
        if struct in rows:
            kind, reason = "rows", "implements ScrollableRows"
        elif struct in surface:
            kind, reason = "pixels", "implements ScrollableSurface"
        elif canonical in SCROLL_EXCLUDED or struct in excluded_structs:
            reason = SCROLL_EXCLUDED.get(canonical, excluded_structs.get(struct, ""))
            kind, reason = "excluded", reason
            if ignore_exclusion in (canonical, struct):
                kind, reason = "unclassified", "injection removed the exclusion"
        else:
            kind, reason = "unclassified", "holds scroll state but implements neither trait"
        entries.append(
            {"control": canonical, "struct": struct, "kind": kind, "reason": reason}
        )
    return entries, registered


def render(entries: list[dict]) -> str:
    counts = {"rows": 0, "pixels": 0, "excluded": 0, "unclassified": 0}
    gaps = 0
    for entry in entries:
        counts[entry["kind"]] = counts.get(entry["kind"], 0) + 1
        if entry["kind"] == "excluded" and entry["reason"].startswith("ROW-UNIT GAP"):
            gaps += 1
    out = [
        "# Scrollable container census (RW-58)",
        "",
        "Generated by `tools/check_scrollable_census.py`. Do not edit by hand.",
        "",
        "Every registered control whose struct stores a scroll position must implement",
        "`ScrollableRows` (rows) or `ScrollableSurface` (pixels), or be excluded with a reason",
        "that names the unit it really uses.",
        "",
        f"- Candidates: **{len(entries)}**",
        f"- `ScrollableRows`: **{counts['rows']}**",
        f"- `ScrollableSurface`: **{counts['pixels']}**",
        f"- Excluded with a reason: **{counts['excluded']}** (of which ROW-UNIT GAP: **{gaps}**)",
        f"- Unclassified: **{counts['unclassified']}**",
        "",
        "| control | struct | coverage | reason |",
        "|---|---|---|---|",
    ]
    for entry in entries:
        out.append(
            f"| `{entry['control']}` | `{entry['struct']}` | {entry['kind']} | {entry['reason']} |"
        )
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", type=pathlib.Path)
    parser.add_argument("--inject", help="canonical name whose exclusion is removed on paper")
    args = parser.parse_args()

    entries, registered = build(ignore_exclusion=args.inject)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(render(entries))

    unclassified = [entry for entry in entries if entry["kind"] == "unclassified"]
    if args.inject:
        if args.inject not in SCROLL_EXCLUDED and not any(
            entry["control"] == args.inject for entry in entries
        ):
            print(f"FAIL: `{args.inject}` is not a candidate control", file=sys.stderr)
            return 1
        if args.inject not in SCROLL_EXCLUDED and not any(
            entry["control"] == args.inject and entry["kind"] == "excluded" for entry in entries
        ):
            print(
                f"FAIL: `{args.inject}` is not excluded, so injecting it proves nothing",
                file=sys.stderr,
            )
            return 1
        if not unclassified:
            print("FAIL: removing an exclusion did not leave the control unclassified")
            return 1
        print(f"FAIL: injected unclassified control {args.inject}")
        return 1

    gaps = sum(
        1
        for entry in entries
        if entry["kind"] == "excluded" and entry["reason"].startswith("ROW-UNIT GAP")
    )
    print(
        f"scrollable census: candidates={len(entries)} "
        f"rows={sum(1 for e in entries if e['kind'] == 'rows')} "
        f"pixels={sum(1 for e in entries if e['kind'] == 'pixels')} "
        f"excluded={sum(1 for e in entries if e['kind'] == 'excluded')} gaps={gaps}"
    )
    if unclassified:
        for entry in unclassified:
            print(f"UNCLASSIFIED {entry['control']}: {entry['reason']}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
