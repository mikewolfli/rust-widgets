"""Emit the BLUE27 icon-entry inventory as a committed artifact.

# Why this exists rather than the assertions alone

`check_icon_entry_contract.sh` answers "is the contract still intact?" but only for the four facts it
knows how to assert (A1-A4). The U0 row of `blue27.md` §19.14.1 stayed open because the inventory
there was an *assertion list*: a reader could not see the full set of entries — only whether the
subset the gate happened to check was still green, and a consumer that nobody thought to assert about
was invisible.

This script is the missing half: it **enumerates** every icon entry from the source text and writes
the result to `tools/icon_entry_inventory.txt`, which is committed. The gate regenerates it and
diffs, so an entry that appears or disappears (a new `set_item_icon_source`, a new published
`icon_source` property, a new inline drawing entry point) changes the artifact and fails the gate
until the artifact is regenerated — the same "generated artifact plus a diff gate" shape the SVG
snapshots and the capability matrix use.

# What it records, and why each column

* **category** — the §19.5 consumer classes (published property / item setter / inline entry point /
  draw primitive), because "where does this icon come from" is the question the inventory exists to
  answer.
* **entry** — the symbol a caller would use.
* **file** — where it is implemented, so the inventory is navigable.
* **gate** — the `cfg` condition that decides whether the entry exists in a given build. §19.9's
  profile rules are only checkable if the gates are written down somewhere.
* **identity** — for collections, what an item is keyed by (`text id`, `u64 id`, `index`, `none`).
  §19.6's rule is that an identity is never invented, and the exemption list in the migration guide
  is what this column makes auditable.

# Determinism

Every list is sorted before it is written, so regenerating produces identical bytes and the diff is
about content rather than about directory iteration order.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

HEADER = """# BLUE27 icon entry inventory - GENERATED by tools/gen_icon_entry_inventory.py
#
# Regenerate with:  python3 tools/gen_icon_entry_inventory.py --output tools/icon_entry_inventory.txt
# Verified by:      tools/check_icon_entry_contract.sh (step 5)
#
# Columns: category | entry | file | gate | identity
# 'gate' is the cfg condition on the enclosing declaration ('-' = unconditional).
# 'identity' applies to collections only: what an item is keyed by (never invented, see blue27 19.6).
"""

# Collections whose item setters are deliberately not record channels, with the identity they have.
# The list mirrors the migration guide's exemption table.
IDENTITY = {
    "mdiarea.rs": "ObjectId (runtime handle)",
    "tabwidget.rs": "index",
    "toolbox.rs": "user_data id",
    "pie_menu.rs": "u64 id (collection-assigned, host-pinnable)",
    "bottom_navigation_bar.rs": "index",
    "navigation_drawer.rs": "index",
    "chip.rs": "text id",
    "tab_bar.rs": "index",
    "core.rs": "index",
    "dropdown_menu.rs": "text id",
    "menu_button.rs": "u64 id",
}


def cfg_above(lines: list[str], index: int) -> str:
    """The `#[cfg(...)]` attributes immediately above `lines[index]`, joined."""
    found: list[str] = []
    cursor = index - 1
    while cursor >= 0 and lines[cursor].strip().startswith(("#[cfg", "#[path", "#[allow", "///", "//")):
        line = lines[cursor].strip()
        if line.startswith("#[cfg"):
            found.append(line)
        cursor -= 1
    return " ".join(reversed(found)) if found else "-"


def collect() -> list[tuple[str, str, str, str, str]]:
    rows: list[tuple[str, str, str, str, str]] = []

    # 1. Published `icon_source` properties (and the legacy `icon_*` channels beside them).
    #
    # The capability tables are a series of `const <CONTROL>_PROPERTIES: &[PropertySchema] = &[ … ]`
    # blocks, so the control a row belongs to is the nearest preceding constant. Recording it is what
    # makes the three separate `icon_source` rows usable: without it they are three identical lines.
    for table in sorted((SRC / "widget/capability").glob("properties_*.in.rs")):
        lines = table.read_text().splitlines()
        control = "-"
        for index, line in enumerate(lines):
            declared = re.search(r"const ([A-Z0-9_]+)_PROPERTIES", line)
            if declared:
                control = declared.group(1).lower()
            match = re.search(r'PropertySchema::new\("(icon_[a-z_]+)"', line)
            if match:
                rows.append(
                    (
                        "published property",
                        match.group(1),
                        str(table.relative_to(ROOT)),
                        cfg_above(lines, index),
                        control,
                    )
                )

    # 2. Item setters on collections, and everything else the source declares as an icon entry:
    #    `set_item_icon_source`, the inline `draw_icon_*` helpers a layout-owning control calls, and
    #    the shared `paint_icon`/`measure_icon`/`validate_icon`/`fit_image_into` seam. Scanning for
    #    them (rather than listing them by hand) is what makes a *new* entry change the artifact and
    #    fail the gate, which is the whole point of committing it.
    patterns = {
        r"\bfn set_item_icon_source\b": ("item setter", "set_item_icon_source"),
        r"\bpub fn (paint_icon|measure_icon|validate_icon|fit_image_into)\b": (
            "draw primitive",
            None,
        ),
        r"\bpub fn (draw_icon_at|draw_icon_named|draw_icon_centered)\b": (
            "inline entry point",
            None,
        ),
        r"\bpub fn (set_icon_source|icon_source|set_shared_icon_pixels|shared_icon_pixels)\b": (
            "typed content api",
            None,
        ),
    }
    for path in sorted(SRC.rglob("*.rs")):
        relative = str(path.relative_to(ROOT))
        if relative.endswith("icon_entry_inventory.txt"):
            continue
        lines = path.read_text().splitlines()
        for index, line in enumerate(lines):
            for pattern, (category, fixed_entry) in patterns.items():
                match = re.search(pattern, line)
                if not match:
                    continue
                entry = fixed_entry or (match.group(1) if match.groups() else match.group(0))
                identity = IDENTITY.get(path.name, "-") if category == "item setter" else "-"
                rows.append((category, entry, relative, cfg_above(lines, index), identity))

    rows.sort()
    return rows


def render(rows: list[tuple[str, str, str, str, str]]) -> str:
    body = "\n".join(" | ".join(row) for row in rows)
    return f"{HEADER}\n{body}\n"


def main() -> int:
    output = ROOT / "tools/icon_entry_inventory.txt"
    if "--output" in sys.argv:
        output = pathlib.Path(sys.argv[sys.argv.index("--output") + 1])
    rows = collect()
    rendered = render(rows)
    if "--check" in sys.argv:
        current = output.read_text() if output.exists() else ""
        if current != rendered:
            print(f"{output} is stale; regenerate with tools/gen_icon_entry_inventory.py", file=sys.stderr)
            return 1
        print(f"{output} matches the source ({len(rows)} entries)")
        return 0
    output.write_text(rendered)
    print(f"wrote {output} ({len(rows)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
