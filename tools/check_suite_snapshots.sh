# ============================================================================
# check_suite_snapshots.sh — the optional-suite SVG snapshots must be current
# ============================================================================
# The parent crate's `snapshots/svg/` is the picture of what a **plain build** draws
# (`tools/check_svg_snapshots.sh`). The controls this package registers need six optional
# feature groups, so they cannot live in that set without making its central claim false.
# They live in `snapshots/suite-svg/` instead, produced by this package's own example.
#
# A committed picture that no gate regenerates is a picture someone looked at once, not an
# artifact that catches a regression (principle #106). This gate therefore:
#
#   [1] checks the set is coherent: every file is a generated artifact, and every control has
#       exactly a dark and a light file;
#   [2] regenerates with the exporter and requires a byte-for-byte match;
#   [3] requires the two appearances to differ, so a theme-blind control cannot pass as a
#       covered one.
#
# The exporter **writes** into `snapshots/suite-svg/`, so this step deliberately does not go
# through `rw_cargo_cached`: a cache hit would replay the output without regenerating, and a
# hand-edited snapshot would then compare equal to itself.
#
# # Reverse injection
#
# Appending one byte to a committed snapshot must make step [2] red; see
# `tools/gates_reverse_injection.md`.
#
# Usage: tools/check_suite_snapshots.sh
# Exit 0 = the suite snapshot set is current and complete.
# Exit 1 = a finding (named above the summary).
# ============================================================================

# rw-gate-budget: 1800
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

. "$ROOT_DIR/tools/lib_timeout.sh"

STEP_BUDGET="${RW_GATE_TIMEOUT:-1800}"
SNAPSHOT_DIR="snapshots/suite-svg"
MARKER="GENERATED by crates/rust-widgets-suites/examples/export_suite_svgs.rs"
FEATURES="finance,maps,project,devtools,media-playback,webview"

hash_set() {
    if command -v sha256sum >/dev/null 2>&1; then
        find "$SNAPSHOT_DIR" -maxdepth 1 -name '*.svg' -print0 | sort -z | xargs -0 sha256sum
    else
        (cd "$SNAPSHOT_DIR" && find . -maxdepth 1 -name '*.svg' | sort | xargs shasum -a 256)
    fi
}

echo "[1/3] every committed suite snapshot is a generated dark/light pair"

if [ ! -d "$SNAPSHOT_DIR" ]; then
    echo "  FAIL  $SNAPSHOT_DIR does not exist; run the exporter documented in"
    echo "        crates/rust-widgets-suites/examples/export_suite_svgs.rs"
    exit 1
fi

for file in "$SNAPSHOT_DIR"/*.svg; do
    [ -e "$file" ] || {
        echo "  FAIL  no suite snapshots are committed"
        exit 1
    }
    if ! head -n 1 "$file" | grep -qF "$MARKER"; then
        echo "  FAIL  $(basename "$file") does not carry the exporter's provenance marker"
        exit 1
    fi
    case "$file" in
        *.light.svg) dark="${file%.light.svg}.svg" ;;
        *) dark="$file" ;;
    esac
    name="$(basename "${dark%.svg}")"
    if [ ! -f "$SNAPSHOT_DIR/$name.svg" ] || [ ! -f "$SNAPSHOT_DIR/$name.light.svg" ]; then
        echo "  FAIL  $name does not have both a dark and a light snapshot"
        exit 1
    fi
done
DARK_COUNT="$(find "$SNAPSHOT_DIR" -maxdepth 1 -name '*.svg' ! -name '*.light.svg' | wc -l | tr -d ' ')"
echo "  PASS  $DARK_COUNT control(s), each with a dark and a light file"

echo "[2/3] regenerate with the suite exporter and compare byte for byte"
BEFORE="$(mktemp)"
AFTER="$(mktemp)"
LOG="$(mktemp)"
trap 'rm -f "$BEFORE" "$AFTER" "$LOG"' EXIT
hash_set > "$BEFORE"

if ! rw_run_bounded "$STEP_BUDGET" cargo run \
    --manifest-path crates/rust-widgets-suites/Cargo.toml \
    --no-default-features --features "$FEATURES" \
    --example export_suite_svgs > "$LOG" 2>&1; then
    echo "  FAIL  the suite snapshot exporter did not run:"
    tail -20 "$LOG" | sed 's/^/        /'
    exit 1
fi
grep -E '^wrote' "$LOG" | sed 's/^/        /' || true

hash_set > "$AFTER"
if ! diff -q "$BEFORE" "$AFTER" > /dev/null; then
    echo "  FAIL  the committed suite snapshots differ from a fresh export:"
    diff "$BEFORE" "$AFTER" | sed -n '1,40p'
    echo "  Regenerate with:"
    echo "    cargo run --manifest-path crates/rust-widgets-suites/Cargo.toml --no-default-features \\"
    echo "      --features \"$FEATURES\" --example export_suite_svgs"
    exit 1
fi
echo "  PASS  regeneration reproduces every committed byte"

echo "[3/3] the two appearances differ for every control"
SAME=""
for dark in "$SNAPSHOT_DIR"/*.svg; do
    case "$dark" in
        *.light.svg) continue ;;
    esac
    name="$(basename "$dark" .svg)"
    if cmp -s "$dark" "$SNAPSHOT_DIR/$name.light.svg"; then
        SAME="$SAME $name"
    fi
done
if [ -n "$SAME" ]; then
    echo "  FAIL  these suite controls render identically in both appearances:$SAME"
    echo "        a pair that proves nothing is worse than no snapshot; fix the control's"
    echo "        theme resolution rather than hiding the file."
    exit 1
fi
echo "  PASS  every dark/light pair differs"

echo ""
echo "check_suite_snapshots: checked=$DARK_COUNT skipped=0 failed=0"
